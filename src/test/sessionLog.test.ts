import { describe, it } from 'node:test';
import * as assert from 'node:assert/strict';
import { SessionNamer, promptText, shortName, titleFrom } from '../utils/sessionLog';

// Entry shapes below are taken from real Claude Code logs (text shortened).
const user = (content: unknown, extra: Record<string, unknown> = {}) => ({ type: 'user', message: { role: 'user', content }, ...extra });

describe('promptText', () => {
  it('drops the <system-reminder> block the desktop app puts before the prompt', () => {
    const entry = user(
      '<system-reminder>\nYou are operating in a git worktree.\nWorktree path: C:\\Source\\app\\.claude\\worktrees\\eager-feynman-8ff4f6\n</system-reminder>\n\nThe webhook lives in the aws-terraform repo'
    );
    assert.equal(promptText(entry), 'The webhook lives in the aws-terraform repo');
  });

  it('shows a slash command as /name args', () => {
    const entry = user(
      '<command-message>mcp-sqlserver:sql-query</command-message>\n<command-name>/mcp-sqlserver:sql-query</command-name>\n<command-args>SELECT TOP 5 * FROM Orders</command-args>'
    );
    assert.equal(promptText(entry), '/mcp-sqlserver:sql-query SELECT TOP 5 * FROM Orders');
    assert.equal(promptText(user('<command-name>/mcp</command-name>\n<command-message>mcp</command-message>\n<command-args></command-args>')), '/mcp');
  });

  it('skips entries the user did not type', () => {
    const notPrompts = [
      user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', { isMeta: true }),
      user([{ type: 'text', text: 'Base directory for this skill: C:\\Users\\me\\.claude\\plugins\\cache' }], { isMeta: true }),
      user('<local-command-stdout>Failed to reconnect to aws-mcp: CONNECTION_CLOSED</local-command-stdout>'),
      user([{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'file contents' }]),
      { type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text: 'Sure' }] } },
      { type: 'summary', summary: 'Something' },
    ];
    for (const entry of notPrompts) {
      assert.equal(promptText(entry), null, JSON.stringify(entry).slice(0, 80));
    }
  });

  it('reads plain strings and text blocks', () => {
    assert.equal(promptText(user('Fix the login redirect loop')), 'Fix the login redirect loop');
    assert.equal(promptText(user([{ type: 'image', source: {} }, { type: 'text', text: 'What is in this screenshot?' }])), 'What is in this screenshot?');
  });
});

describe('titleFrom', () => {
  it('reads custom-title entries and the older summary entries', () => {
    assert.equal(titleFrom({ type: 'custom-title', customTitle: 'Fix login redirect loop', sessionId: 'x' }), 'Fix login redirect loop');
    assert.equal(titleFrom({ type: 'summary', summary: 'Login fix', leafUuid: 'y' }), 'Login fix');
    assert.equal(titleFrom({ type: 'custom-title', customTitle: '  ' }), null);
    assert.equal(titleFrom(user('hello')), null);
  });
});

describe('SessionNamer', () => {
  it('prefers the latest recorded title over the first prompt', () => {
    const namer = new SessionNamer();
    namer.add(user('<system-reminder>worktree info</system-reminder>\n\nplease fix the flaky test'));
    assert.equal(namer.name, 'please fix the flaky test');
    assert.equal(namer.hasTitle, false);
    namer.add({ type: 'custom-title', customTitle: 'Fix flaky test' });
    namer.add(user('second prompt'));
    namer.add({ type: 'custom-title', customTitle: 'Fix flaky checkout test' }); // a later /rename
    assert.equal(namer.name, 'Fix flaky checkout test');
    assert.equal(namer.hasTitle, true);
  });

  it('has no name for a session with no prompt or title yet', () => {
    const namer = new SessionNamer();
    namer.add(user('<local-command-stdout>ok</local-command-stdout>'));
    assert.equal(namer.name, null);
  });
});

describe('shortName', () => {
  it('collapses whitespace and cuts long text at a word boundary', () => {
    assert.equal(shortName('  fix\n\nthe   bug  '), 'fix the bug');
    assert.equal(
      shortName('Investigate why the nightly deploy job fails on the staging cluster'),
      'Investigate why the nightly deploy job fails on...'
    );
  });
});
